/// Returns the canonical thumbnail name matching `name` case-insensitively.
pub fn lookup(name: &str) -> Option<&'static str> {
    NAMES.iter().copied().find(|n| n.eq_ignore_ascii_case(name))
}

/// Picks a thumbnail for an issuer: an exact (case-insensitive) match first, then the first
/// thumbnail name that appears as a whole word inside the issuer, otherwise [`DEFAULT`].
pub fn for_issuer(issuer: &str) -> &'static str {
    if let Some(name) = lookup(issuer.trim()) {
        return name;
    }
    let lower = issuer.to_lowercase();
    NAMES
        .iter()
        .copied()
        .filter(|n| *n != DEFAULT)
        .find(|n| contains_word(&lower, &n.to_lowercase()))
        .unwrap_or(DEFAULT)
}

fn contains_word(haystack: &str, word: &str) -> bool {
    let is_word = |c: char| c.is_alphanumeric() || c == '_';
    haystack.match_indices(word).any(|(start, _)| {
        let before = haystack[..start].chars().next_back();
        let after = haystack[start + word.len()..].chars().next();
        !before.is_some_and(is_word) && !after.is_some_and(is_word)
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matching() {
        assert_eq!(for_issuer("github"), "GitHub");
        assert_eq!(for_issuer("My GitLab server"), "GitLab");
        assert_eq!(for_issuer("Gitlabber"), DEFAULT);
        assert_eq!(for_issuer("Unknown corp"), DEFAULT);
        assert_eq!(lookup("steam"), Some("Steam"));
    }
}
